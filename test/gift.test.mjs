import test from 'node:test';
import assert from 'node:assert/strict';
import {
  asksAboutGift,
  asksAboutShare,
  isHeavyMoment,
  canSuggestShare,
} from '../lib/gift.js';

/**
 * «Өгөө авъяа» системийн тест.
 *
 * ⚠️ Энэ файлын ХАМГИЙН ЧУХАЛ хэсэг нь «ТӨЛБӨРИЙН АСУУЛТ БИШ» блок.
 *    Худал эерэг илрэлт = хүн сэтгэлээ нээж байхад бот данс сунгана.
 *    Энэ бол системийн хамгийн муу алдаа, тиймээс хамгийн их тест энд байна.
 */

test('хүн ӨӨРӨӨ асуусан тохиолдлууд', () => {
  const asks = [
    'Энэ төлбөртэй юу?',
    'үнэгүй юу',
    'Үнэгүй юм уу?',
    'Үнэхээр үнэгүй юу?',
    'Хэдэн төгрөг вэ?',
    'ямар үнэтэй вэ',
    'Дансны дугаараа өгөөч',
    'данс байна уу',
    'Данс нь хэд вэ?',
    'Би чамайг яаж дэмжих вэ?',
    'Хэрхэн дэмжих вэ',
    'хандив өгмөөр байна',
    'Мөнгө шилжүүлмээр байна',
    'Танд мөнгө өгч болох уу?',
    'төлье гэсэн юм',
    'төлмөөр байна',
    'Хариу барих юм байна уу',
    'QPay байгаа юу',
    'IBAN дугаараа явуулаач',
    'Яаж талархах вэ?',
    'tulburtei yu',
    'unegui yu',
  ];
  for (const text of asks) {
    assert.equal(asksAboutGift(text), true, `асуулт гэж танигдах ёстой: ${text}`);
  }
});

test('төлбөрийн асуулт БИШ — худал эерэг байж болохгүй', () => {
  const notAsks = [
    // «үнэ цэнэ» бол энэ бүтээгдэхүүний гол сэдэв
    'Энэ надад маш их үнэ цэнтэй байлаа',
    'Өөрийгөө үнэлж сурмаар байна',
    'Чиний хэлсэн үг үнэн байна',
    'Үнэхээр тусалсан шүү, баярлалаа',
    // амьдралын ярианд мөнгө дурдагдах нь энгийн зүйл
    'Мөнгөний асуудал надад их стресс болдог',
    'Ажил дээрээ мөнгөн шагнал авсан',
    'Гэр бүлдээ мөнгө өгдөг болохоор ядарч байна',
    'Би хэдэн жил мөнгөгүй явсан',
    'Мөнгө надад аз жаргал авчирдаггүй юм байна',
    // «дэмжих» нь хүн хоорондын харилцааны үг
    'Найз маань намайг их дэмжиж байна',
    'Ээж маань намайг дэмждэг',
    'Би түүнийг дэмжмээр байна',
    'Хэн ч намайг дэмждэггүй юм шиг санагддаг',
    // «шилжүүлэх» нь анхаарлын тухай ч байж болно
    'Анхаарлаа өөр зүйл рүү шилжүүлэх гэж оролдсон',
    // ердийн яриа
    'Өнөөдөр ажилдаа их ядарлаа',
    'Би өөрийгөө ойлгохыг хүсч байна',
    'Тэгээд яах вэ?',
    'Баярлалаа',
  ];
  for (const text of notAsks) {
    assert.equal(asksAboutGift(text), false, `асуулт гэж танигдах ЁСГҮЙ: ${text}`);
  }
});

test('хоосон / утгагүй оролт', () => {
  for (const text of ['', '   ', null, undefined, '?', '🙂']) {
    assert.equal(asksAboutGift(text), false, `оролт: ${JSON.stringify(text)}`);
  }
});

test('«тусалсан» дотор «салсан» гэсэн үгийг олж болохгүй', () => {
  // Дэд мөрөөр таарвал талархлыг гашуудлын дохио гэж уншиж, системийн
  // шийдвэр бүрэн эргэнэ. Үгийн эхнээс таарах ёстой.
  assert.equal(isHeavyMoment('Чи надад үнэхээр тусалсан шүү'), false);
  assert.equal(isHeavyMoment('Бид саяхан салсан'), true);
});

test('хуваалцахыг асуух', () => {
  assert.equal(asksAboutShare('Хаана хуваалцах вэ'), true);
  assert.equal(asksAboutShare('найздаа хэлэх үү'), true);
  assert.equal(asksAboutShare('Өнөөдөр сайхан байна'), false);
});

test('хүнд мөчийг таних', () => {
  assert.equal(isHeavyMoment('амиа хорлох бодол төрж байна'), true);
  assert.equal(isHeavyMoment('өнөөдөр их уйллаа'), true);
  assert.equal(isHeavyMoment('сайхан өдөр байлаа'), false);
});

// ── Зөөлөн сануулга: бүх нөхцөл ЗЭРЭГ хангагдах ёстой ───────────────────

const DAY = 24 * 60 * 60 * 1000;
const ready = () => ({
  profile: { type_name: 'x' },
  createdAt: Date.now() - 10 * DAY,
  activeDays: ['2026-09-01', '2026-09-05', '2026-09-10'],
  messageCount: 20,
  shareNudgedAt: null,
});
const PROGRESS = 'Их баярлалаа, надад үнэхээр тусалсан';

test('зөөлөн сануулга — бүх нөхцөл хангагдсан', () => {
  assert.equal(canSuggestShare(ready(), PROGRESS), true);
});

test('зөөлөн сануулга — нөхцөл дутвал ХЭЗЭЭ Ч үгүй', () => {
  const cases = [
    ['ахиц гараагүй', ready(), 'За тэгэх үү'],
    ['хүнд мөч', ready(), 'Баярлалаа гэхдээ би үхмээр байна'],
    ['долоо хоног болоогүй', { ...ready(), createdAt: Date.now() - DAY }, PROGRESS],
    ['цөөн өдөр эргэж ирсэн', { ...ready(), activeDays: ['2026-09-01'] }, PROGRESS],
    ['яриа богино', { ...ready(), messageCount: 3 }, PROGRESS],
    ['аль хэдийн сануулсан', { ...ready(), shareNudgedAt: Date.now() }, PROGRESS],
    ['тестээ өгөөгүй', { ...ready(), profile: null }, PROGRESS],
  ];
  for (const [label, session, text] of cases) {
    assert.equal(canSuggestShare(session, text), false, label);
  }
});
