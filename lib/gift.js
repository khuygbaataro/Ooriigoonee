/**
 * ⚠️ Энэ хоёр нь ЗӨВХӨН зөөлөн сануулгыг ЗОГСООХ / ЗӨВШӨӨРӨХӨД ашиглагдана.
 *    Худал эерэг илрэх нь аюулгүй (сануулга хийхгүй өнгөрнө), харин худал
 *    сөрөг нь аюултай (хүнд мөчид сануулга явчихна). Тиймээс HEAVY жагсаалт
 *    өгөөмөр байх нь зөв.
 */
export const isHeavyMoment = (text) => anyWord(normalize(text), HEAVY);
const showsProgress = (text) => anyWord(normalize(text), PROGRESS);

// ── 3. Зөөлөн сануулга зөвшөөрөгдөх үү? ─────────────────────────────────

const DAY_MS = 24 * 60 * 60 * 1000;

/** Хамгийн эрт зөөлөн сануулга хийж болох хугацаа. */
const MIN_DAYS = 7;
/** Тусдаа хэдэн өдөр эргэж ирсэн байх ёстой вэ. */
const MIN_ACTIVE_DAYS = 3;
/** Хэдэн мессеж солилцсоны дараа вэ. */
const MIN_MESSAGES = 12;

/**
 * ХУВААЛЦАХ тухай зөөлөн сануулга илгээж болох уу?
 *
 * ⚠️ Энэ нь МӨНГӨ гуйхгүй. Зөвхөн «тустай байсан бол нэг хүнд хэлээрэй»
 *    гэсэн санал. Бүх нөхцөл ЗЭРЭГ хангагдсан үед л, АМЬДРАЛД НЭГ УДАА.
 */
export function canSuggestShare(session, text) {
  if (!config.giftEnabled) return false;
  if (session.shareNudgedAt) return false;          // амьдралд ганц удаа
  if (!session.profile) return false;               // аяллаа дуусгаагүй
  if (isHeavyMoment(text)) return false;            // хүнд мөчид хэзээ ч үгүй
  if (!showsProgress(text)) return false;           // ахиц гараагүй бол үгүй

  const ageDays = (Date.now() - (session.createdAt ?? Date.now())) / DAY_MS;
  if (ageDays < MIN_DAYS) return false;

  if ((session.activeDays?.length ?? 0) < MIN_ACTIVE_DAYS) return false;
  if ((session.messageCount ?? 0) < MIN_MESSAGES) return false;

  return true;
}

