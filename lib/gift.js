/**
 * Мөнгөтэй холбоотой боловч дангаараа хангалтгүй үгс.
 *
 * «төгрөг» ЗОРИУД байхгүй — хэтэрхий өргөн («төгрөг гэж юу вэ»), харин
 * хэрэгтэй хослолууд нь DIRECT дотор бүтнээрээ бий («хэдэн төгрөг»).
 */
const MONEY_WORD = [
  'төлбөр', 'мөнгө', 'данс', 'шилжүүлэг', 'гүйлгээ',
  'mungu', 'mongo', 'dans', 'tolbor',
];

/**
 * Асуултын бөөм / гуйлтын дагавар — мессеж БОТ РУУ чиглэсэн гэдгийн шинж.
 *
 * ⚠️ Зөвхөн асуултын бөөм (уу/үү/юу/юү/вэ/бэ). «яаж», «хэдэн», «ямар» гэх
 *    асуух төлөөний үгсийг ЗОРИУД оруулаагүй: «би хэдэн жил мөнгөгүй явсан»
 *    гэсэн амьдралын яриаг төлбөрийн асуулт гэж уншина. Тэдгээр хэрэгтэй
 *    хослолууд DIRECT дотор бүтэн хэллэгээрээ аль хэдийн байгаа
 *    («хэдэн төгрөг», «яаж дэмжих», «дансны дугаар»).
 */
const PARTICLE = /\s(уу|үү|юу|юү|вэ|бэ|билээ)\s/;
/** Гуйлтын дагавар: өгөӨӨЧ, хэлЭЭЧ, явуулААЧ. */
const REQUEST = /(аач|ээч|ооч|өөч)\s/;

/**
 * Хэрэглэгч ӨӨРӨӨ төлбөр / дэмжлэгийн тухай асууж байна уу?
 *
 * ⚠️ Энэ функц `true` буцаасан үед Л дансны мэдээлэл харагдана.
 *    Өөр ямар ч замаар мөнгөний тухай мессеж илгээгдэхгүй.
 */
export function asksAboutGift(text) {
  const raw = String(text ?? '');
  const t = normalize(raw);
  if (!t.trim()) return false;

  // 1. Өөр утгаар ойлгогдох боломжгүй хэллэг — дангаараа хангалттай.
  if (anyWord(t, DIRECT)) return true;

  // 2. Мөнгөний үг ДАНГААРАА хангалтгүй — асуултын шинжтэй байх ёстой.
  const asking = raw.includes('?') || PARTICLE.test(t) || REQUEST.test(t);
  return anyWord(t, MONEY_WORD) && asking;
}

